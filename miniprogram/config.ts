/* 服务端地址
 *
 * ★ 这个值决定了小程序能不能跑起来，而且它是**唯一**需要按环境改的地方。
 *
 * ── 三种情况 ────────────────────────────────────────────────────
 * 1. 本地开发（开发者工具）
 *    http://127.0.0.1:5199
 *    必须在「详情 → 本地设置」里勾上「不校验合法域名、web-view、
 *    TLS 版本以及 HTTPS 证书」。否则请求会被直接拦掉，
 *    报的错是「不在以下 request 合法域名列表中」，和网络问题很像。
 *
 * 2. 真机预览
 *    127.0.0.1 在手机上是手机自己，连不到你的电脑。
 *    要改成电脑在局域网里的 IP（如 http://192.168.1.10:5199），
 *    并且服务端 HOST 要绑 0.0.0.0 而不是 127.0.0.1。
 *    同样需要勾「不校验合法域名」，而且手机和电脑要同一个 WiFi。
 *
 * 3. 正式发布
 *    必须是 **HTTPS + 已 ICP 备案** 的域名，并在
 *    「微信公众平台 → 开发 → 开发设置 → 服务器域名」里配进
 *    request 合法域名。这一步绕不过去 —— 个人主体也要备案。
 *    域名没备案的话，只能停在开发者工具和真机预览阶段。
 *
 * ── 关于公式图的地址 ────────────────────────────────────────────
 * 服务端返回的公式图是相对路径（/math/xxx.png），由 api/render.ts
 * 拼上 BASE_URL 变成绝对地址。而 <image> 组件加载网络图片
 * **不受**合法域名限制（只有 wx.request / downloadFile 受限），
 * 所以公式图不需要额外配 downloadFile 域名。
 */
export const BASE_URL = 'http://127.0.0.1:5199';

/** 主题前景色。服务端按这个颜色光栅化公式图，缓存键里也带着它。
 *
 *  ★ 这个值必须和 app.wxss 里的 --fg 一致。
 *    不一致的后果是：深色主题下公式图被渲成深墨色，直接看不见 ——
 *    而且因为图片缓存住了，改主题也不会自动恢复，得清缓存。
 *    这是「服务端渲染 + 客户端主题」这套组合最容易踩的坑。 */
export const INK = '#e8eaf2';
